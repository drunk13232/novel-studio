import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('../src/navigation-query.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {chapterMatches,bookMatches}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
assert(chapterMatches({number:8,title:'迷雾港'},'008'));
assert(chapterMatches({number:8,title:'迷雾港'},'第8章'));
assert(chapterMatches({number:8,title:'迷雾港'},' 迷雾 '));
assert(chapterMatches({number:8,title:'The Return'},'return'));
assert(chapterMatches({number:8},''));
assert(!chapterMatches({number:8,title:'迷雾港'},'第9章'));
assert(!chapterMatches({number:8,title:'迷雾港'},'[.*]'));
const book={title:'The Tide Post Office',genre:'Coastal Fantasy',writing:{form:'novella'}};
assert(bookMatches(book,'  tide FANTASY  ','novella'));
assert(!bookMatches(book,'tide','short'));
assert(!bookMatches(book,'missing'));
assert(bookMatches({title:'无题'},''));
assert(bookMatches({title:'无题'},'无题','novel'));
console.log('12 local chapter/bookshelf search cases PASS; no alternate search index or model request.');
